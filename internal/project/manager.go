type Project struct {
	Name        string    `json:"name"`
	Summary     string    `json:"summary"`
	CreatedAt   time.Time `json:"created_at"`
	UpdatedAt   time.Time `json:"updated_at"`
	Path        string    `json:"path"`
	IndexHTML   string    `json:"index_html"`
	GitEnabled  bool      `json:"git_enabled"`
	Collaborators []string `json:"collaborators,omitempty"`
}

type CommitInfo struct {
	Hash      string    `json:"hash"`
	Message   string    `json:"message"`
	Author    string    `json:"author"`
	Email     string    `json:"email"`
	Timestamp time.Time `json:"timestamp"`
	Files     []string  `json:"files"`
}

type Collaborator struct {
	Name     string    `json:"name"`
	Email    string    `json:"email"`
	Role     string    `json:"role"` // owner, contributor, viewer
	AddedAt  time.Time `json:"added_at"`
}

type Manager struct {
	basePath string
}

func NewManager() *Manager {
	homeDir, _ := os.UserHomeDir()
	return &Manager{
		basePath: filepath.Join(homeDir, "GoShareProjects"),
	}
}

func (m *Manager) getProjectPath(name string) string {
	return filepath.Join(m.basePath, name)
}

func (m *Manager) Create(name, summary string) error {
	projectPath := m.getProjectPath(name)

	if _, err := os.Stat(projectPath); err == nil {
		return fmt.Errorf("project '%s' already exists", name)
	}

	if err := os.MkdirAll(projectPath, 0755); err != nil {
		return fmt.Errorf("failed to create project directory: %w", err)
	}

	if summary == "" {
		fmt.Print("Enter project summary: ")
		reader := bufio.NewReader(os.Stdin)
		input, _ := reader.ReadString('\n')
		summary = strings.TrimSpace(input)
	}

	project := &Project{
		Name:      name,
		Summary:   summary,
		CreatedAt: time.Now(),
		UpdatedAt: time.Now(),
		Path:      projectPath,
	}

	if err := m.saveProject(project); err != nil {
		return err
	}

	if err := m.generateIndexHTML(project); err != nil {
		return err
	}

	color.Green("Project '%s' created successfully at %s", name, projectPath)
	return nil
}

func (m *Manager) saveProject(project *Project) error {
	data, err := json.MarshalIndent(project, "", "  ")
	if err != nil {
		return fmt.Errorf("failed to marshal project: %w", err)
	}

	projectFile := filepath.Join(project.Path, ".goshare.json")
	return os.WriteFile(projectFile, data, 0644)
}

func (m *Manager) loadProject(name string) (*Project, error) {
	projectPath := m.getProjectPath(name)
	projectFile := filepath.Join(projectPath, ".goshare.json")

	data, err := os.ReadFile(projectFile)
	if err != nil {
		return nil, fmt.Errorf("project '%s' not found", name)
	}

	var project Project
	if err := json.Unmarshal(data, &project); err != nil {
		return nil, fmt.Errorf("failed to unmarshal project: %w", err)
	}

	return &project, nil
}

