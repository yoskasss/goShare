package project

import (
	"bufio"
	"encoding/json"
	"fmt"
	"html/template"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/common-nighthawk/go-figure"
	"github.com/fatih/color"
	cp "github.com/n-marshall/go-cp"
)

type Project struct {
	Name      string    `json:"name"`
	Summary   string    `json:"summary"`
	CreatedAt time.Time `json:"created_at"`
	UpdatedAt time.Time `json:"updated_at"`
	Path      string    `json:"path"`
	IndexHTML string    `json:"index_html"`
}

type Manager struct {
	basePath string
}

func NewManager() *Manager {
	homeDir, _ := os.UserHomeDir()
	return &Manager{
		basePath: filepath.Join(homeDir, "GoShareProjects"),
	}
}

func (m *Manager) getProjectPath(name string) string {
	return filepath.Join(m.basePath, name)
}

func (m *Manager) Create(name, summary string) error {
	projectPath := m.getProjectPath(name)

	if _, err := os.Stat(projectPath); err == nil {
		return fmt.Errorf("project '%s' already exists", name)
	}

	if err := os.MkdirAll(projectPath, 0755); err != nil {
		return fmt.Errorf("failed to create project directory: %w", err)
	}

	if summary == "" {
		fmt.Print("Enter project summary: ")
		reader := bufio.NewReader(os.Stdin)
		input, _ := reader.ReadString('\n')
		summary = strings.TrimSpace(input)
	}

	project := &Project{
		Name:      name,
		Summary:   summary,
		CreatedAt: time.Now(),
		UpdatedAt: time.Now(),
		Path:      projectPath,
	}

	if err := m.saveProject(project); err != nil {
		return err
	}

	if err := m.generateIndexHTML(project); err != nil {
		return err
	}

	color.Green("Project '%s' created successfully at %s", name, projectPath)
	return nil
}

func (m *Manager) saveProject(project *Project) error {
	data, err := json.MarshalIndent(project, "", "  ")
	if err != nil {
		return fmt.Errorf("failed to marshal project: %w", err)
	}

	projectFile := filepath.Join(project.Path, ".goshare.json")
	return os.WriteFile(projectFile, data, 0644)
}

func (m *Manager) loadProject(name string) (*Project, error) {
	projectPath := m.getProjectPath(name)
	projectFile := filepath.Join(projectPath, ".goshare.json")

	data, err := os.ReadFile(projectFile)
	if err != nil {
		return nil, fmt.Errorf("project '%s' not found", name)
	}

	var project Project
	if err := json.Unmarshal(data, &project); err != nil {
		return nil, fmt.Errorf("failed to unmarshal project: %w", err)
	}

	return &project, nil
}

func (m *Manager) generateIndexHTML(project *Project) error {
	tmpl := `<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{{.Name}} - GoShare</title>
    <style>
        body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif; max-width: 900px; margin: 0 auto; padding: 20px; line-height: 1.6; }
        .header { border-bottom: 1px solid #e1e4e8; padding-bottom: 20px; margin-bottom: 30px; }
        .title { font-size: 2.5em; font-weight: 600; color: #24292e; margin: 0; }
        .summary { font-size: 1.2em; color: #586069; margin-top: 10px; }
        .meta { color: #6a737d; font-size: 0.9em; margin-top: 15px; }
        .file-tree { background: #f6f8fa; border-radius: 6px; padding: 20px; overflow-x: auto; }
        .file-tree pre { margin: 0; font-family: "SF Mono", "Fira Code", monospace; font-size: 0.9em; }
        .footer { margin-top: 40px; padding-top: 20px; border-top: 1px solid #e1e4e8; color: #6a737d; font-size: 0.9em; text-align: center; }
        .badge { display: inline-block; padding: 2px 8px; border-radius: 12px; font-size: 0.75em; font-weight: 600; background: #e3f2fd; color: #1976d2; }
    </style>
</head>
<body>
    <div class="header">
        <h1 class="title">{{.Name}}</h1>
        <p class="summary">{{.Summary}}</p>
        <div class="meta">
            <span class="badge">GoShare</span>
            Created: {{.CreatedAt.Format "2006-01-02 15:04"}}
            {{if ne .CreatedAt .UpdatedAt}} | Updated: {{.UpdatedAt.Format "2006-01-02 15:04"}}{{end}}
        </div>
    </div>
    <div class="file-tree">
        <h2>Project Files</h2>
        <pre>{{.FileTree}}</pre>
    </div>
    <div class="footer">
        Generated by <a href="https://github.com/GoShare">GoShare</a>
    </div>
</body>
</html>`

	fileTree := m.generateFileTree(project.Path)

	t, err := template.New("index").Parse(tmpl)
	if err != nil {
		return fmt.Errorf("failed to parse template: %w", err)
	}

	data := struct {
		*Project
		FileTree string
	}{
		Project:  project,
		FileTree: fileTree,
	}

	indexPath := filepath.Join(project.Path, "index.html")
	f, err := os.Create(indexPath)
	if err != nil {
		return fmt.Errorf("failed to create index.html: %w", err)
	}
	defer f.Close()

	if err := t.Execute(f, data); err != nil {
		return fmt.Errorf("failed to execute template: %w", err)
	}

	project.IndexHTML = indexPath
	return m.saveProject(project)
}

func (m *Manager) generateFileTree(root string) string {
	var builder strings.Builder
	m.walkDir(root, "", &builder, true)
	return builder.String()
}

func (m *Manager) walkDir(path, prefix string, builder *strings.Builder, isRoot bool) {
	entries, err := os.ReadDir(path)
	if err != nil {
		return
	}

	var filteredEntries []os.DirEntry
	for _, e := range entries {
		if !strings.HasPrefix(e.Name(), ".") || e.Name() == ".goshare.json" {
			filteredEntries = append(filteredEntries, e)
		}
	}

	for i, entry := range filteredEntries {
		isLast := i == len(filteredEntries)-1
		connector := "├── "
		newPrefix := prefix + "│   "
		if isLast {
			connector = "└── "
			newPrefix = prefix + "    "
		}

		if isRoot {
			builder.WriteString(entry.Name() + "\n")
		} else {
			builder.WriteString(prefix + connector + entry.Name() + "\n")
		}

		if entry.IsDir() {
			fullPath := filepath.Join(path, entry.Name())
			m.walkDir(fullPath, newPrefix, builder, false)
		}
	}
}

func (m *Manager) Copy(projectName, sourcePath string) error {
	project, err := m.loadProject(projectName)
	if err != nil {
		return err
	}

	absSource, err := filepath.Abs(sourcePath)
	if err != nil {
		return fmt.Errorf("failed to resolve source path: %w", err)
	}

	info, err := os.Stat(absSource)
	if err != nil {
		return fmt.Errorf("source not found: %w", err)
	}

	destPath := filepath.Join(project.Path, filepath.Base(absSource))

	color.Cyan("Copying %s to %s...", absSource, destPath)

	if info.IsDir() {
		if err := m.copyDirectory(absSource, destPath); err != nil {
			return fmt.Errorf("failed to copy directory: %w", err)
		}
	} else {
		if err := cp.CopyFile(absSource, destPath); err != nil {
			return fmt.Errorf("failed to copy file: %w", err)
		}
	}

	project.UpdatedAt = time.Now()
	if err := m.generateIndexHTML(project); err != nil {
		return err
	}

	color.Green("Copied successfully!")
	return nil
}

func (m *Manager) copyDirectory(src, dst string) error {
	return filepath.Walk(src, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}

		relPath, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}

		destPath := filepath.Join(dst, relPath)

		if info.IsDir() {
			return os.MkdirAll(destPath, info.Mode())
		}

		return cp.CopyFile(path, destPath)
	})
}

func (m *Manager) Delete(name string) error {
	projectPath := m.getProjectPath(name)

	if _, err := os.Stat(projectPath); os.IsNotExist(err) {
		return fmt.Errorf("project '%s' not found", name)
	}

	if err := os.RemoveAll(projectPath); err != nil {
		return fmt.Errorf("failed to delete project: %w", err)
	}

	color.Green("Project '%s' deleted successfully", name)
	return nil
}

func (m *Manager) List() ([]*Project, error) {
	entries, err := os.ReadDir(m.basePath)
	if err != nil {
		if os.IsNotExist(err) {
			return []*Project{}, nil
		}
		return nil, err
	}

	var projects []*Project
	for _, entry := range entries {
		if entry.IsDir() {
			project, err := m.loadProject(entry.Name())
			if err == nil {
				projects = append(projects, project)
			}
		}
	}

	return projects, nil
}

func (m *Manager) GetProject(name string) (*Project, error) {
	return m.loadProject(name)
}

func (m *Manager) PrintBanner() {
	myFigure := figure.NewFigure("GoShare", "slant", true)
	myFigure.Print()
	color.Cyan("Lightweight project sharing tool")
	fmt.Println()
}
